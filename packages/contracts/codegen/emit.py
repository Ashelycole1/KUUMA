def kt_name(n: str) -> str:
    return f"`{n}`" if n in KT_RESERVED else n


def kt_type(t, model: Model) -> str:
    if isinstance(t, TRef):
        return t.name
    if isinstance(t, TList):
        return f"List<{kt_type(t.item, model)}>"
    return {"string": "String", "integer": "Long", "number": "Double", "boolean": "Boolean"}[t.kind]


def kt_kdoc(text: str, indent: str = "") -> list[str]:
    lines = doc_lines(text)
    if not lines:
        return []
    return [f"{indent}/**", *[f"{indent} * {line}".rstrip() for line in lines], f"{indent} */"]


def emit_kotlin(model: Model) -> dict[str, str]:
    pkg = "ug.kuuma.contracts"
    out: dict[str, str] = {}

    # --- Types.kt: enums + aliases
    lines = [
        f"// {HEADER}",
        '@file:Suppress("unused")',
        "",
        f"package {pkg}",
        "",
        "import kotlinx.serialization.SerialName",
        "import kotlinx.serialization.Serializable",
        "",
    ]
    for a in model.sorted_types("alias"):
        lines += kt_kdoc(a.doc + (f"\n\nPattern: `{a.pattern}`" if a.pattern else ""))
        lines += [f"typealias {a.name} = String", ""]
    for e in model.sorted_types("enum"):
        lines += kt_kdoc(e.doc)
        lines += ["@Serializable", f"enum class {e.name}(val wire: String) {{"]
        for v in e.values:
            lines.append(f'    @SerialName("{v}") {v.upper()}("{v}"),')
        lines += [
            "    ;",
            "",
            "    companion object {",
            f"        fun fromWire(wire: String): {e.name} =",
            "            entries.firstOrNull { it.wire == wire }",
            f'                ?: throw IllegalArgumentException("Unknown {e.name}: $wire")',
            "    }",
            "}",
            "",
        ]
    lines += [
        "/** Patterns for the string aliases above, for runtime validation. */",
        "object ContractPatterns {",
    ]
    for a in model.sorted_types("alias"):
        if a.pattern:
            kt_literal = json.dumps(a.pattern).replace("$", "\\$")
            lines.append(f"    val {camel_to_snake(a.name).upper()} = Regex({kt_literal})")
    lines += ["}", ""]
    out["src/main/kotlin/ug/kuuma/contracts/Types.kt"] = "\n".join(lines)

    # --- Models.kt: object types (shared + API)
    lines = [f"// {HEADER}", "", f"package {pkg}", "", "import kotlinx.serialization.Serializable", ""]
    for o in model.sorted_types("object"):
        if o.is_payload:
            continue
        lines += kt_object(o, model)
    out["src/main/kotlin/ug/kuuma/contracts/Models.kt"] = "\n".join(lines)

    # --- Events.kt
    lines = [
        f"// {HEADER}",
        "",
        f"package {pkg}",
        "",
        "import kotlinx.serialization.KSerializer",
        "import kotlinx.serialization.Serializable",
        "",
        "/** The build namespaces that may publish events. A namespace may only publish its own topics. */",
        "enum class Namespace(val wire: String) {",
    ]
    for ns in model.namespaces:
        lines.append(f'    {ns.upper()}("{ns}"),')
    lines += [
        "    ;",
        "",
        "    companion object {",
        "        fun fromWire(wire: String): Namespace = entries.first { it.wire == wire }",
        "    }",
        "}",
        "",
        "/** Where an event may travel. */",
        "enum class Where(val wire: String) {",
    ]
    for w in sorted({e.where for e in model.events}):
        lines.append(f'    {w.upper()}("{w}"),')
    lines += [
        "}",
        "",
        "/** Every event payload is one of the two marker interfaces below. */",
        "sealed interface EventPayload",
        "",
        "/** May leave the phone. Network clients accept only these. */",
        "interface CloudSendablePayload : EventPayload",
        "",
        "/** Must never leave the phone. Holds real message text or names. */",
        "interface PhoneOnlyPayload : EventPayload",
        "",
        "/** Wraps every event. No envelope field ever holds a real name, phone number or message text. */",
        "@Serializable",
        "data class Envelope<P : EventPayload>(",
        "    val eventId: Uuid,",
        "    val type: String,",
        "    val version: Int,",
        "    val occurredAt: Timestamp,",
        "    /** Random per-install ID. Not a hardware ID. */",
        "    val deviceId: Uuid,",
        "    /** Pseudonymous, random. Absent before a case exists. */",
        "    val caseId: Uuid? = null,",
        "    val payload: P,",
        ")",
        "",
    ]
    for o in model.sorted_types("object"):
        if o.is_payload:
            lines += kt_object(
                o, model, marker="PhoneOnlyPayload" if o.phone_only else "CloudSendablePayload"
            )
    lines += [
        "/** Static description of one event type, used by the bus and the contract tests. */",
        "class EventType<P : EventPayload>(",
        "    val type: String,",
        "    val version: Int,",
        "    val publisher: Namespace,",
        "    val where: Where,",
        "    val phoneOnly: Boolean,",
        "    val serializer: KSerializer<P>,",
        ") {",
        '    override fun toString(): String = "$type.v$version"',
        "}",
        "",
        "object Events {",
    ]
    for e in model.events:
        lines += [
            f"    /** {doc_lines(e.doc)[0] if e.doc else e.type} */",
            f"    val {e.const_name}: EventType<{e.payload}> = EventType(",
            f'        "{e.type}", {e.version}, Namespace.{e.publisher.upper()}, Where.{e.where.upper()},',
            f"        phoneOnly = {str(e.phone_only).lower()}, serializer = {e.payload}.serializer(),",
            "    )",
        ]
    lines += ["", "    val all: List<EventType<out EventPayload>> = listOf("]
    lines += [f"        {e.const_name}," for e in model.events]
    lines += [
        "    )",
        "",
        "    fun byType(type: String, version: Int): EventType<out EventPayload>? =",
        "        all.firstOrNull { it.type == type && it.version == version }",
        "}",
        "",
    ]
    out["src/main/kotlin/ug/kuuma/contracts/Events.kt"] = "\n".join(lines)
    out["src/main/resources/kuuma/schema-bundle.json"] = schema_bundle_json(model)
    return out


def kt_object(o: ObjectDef, model: Model, marker: str | None = None) -> list[str]:
    lines = kt_kdoc(o.doc)
    lines += ["@Serializable", f"data class {o.name}("]
    for f in o.fields:
        lines += kt_kdoc(f.doc, "    ")
        t = kt_type(f.type, model)
        if f.required:
            lines.append(f"    val {kt_name(f.name)}: {t},")
        else:
            lines.append(f"    val {kt_name(f.name)}: {t}? = null,")
    lines.append(f"){' : ' + marker if marker else ''}")
    lines.append("")
    return lines


