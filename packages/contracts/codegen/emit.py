def dart_object(o: ObjectDef, model: Model) -> list[str]:
    base = ""
    if o.is_payload:
        base = " extends PhoneOnlyPayload" if o.phone_only else " extends CloudSendablePayload"
    L = dart_doc(o.doc)
    L.append(f"class {o.name}{base} {{")
    params = []
    for f in o.fields:
        params.append(f"{'required ' if f.required else ''}this.{dart_ident(f.name)}")
    L.append(f"  const {o.name}({{{', '.join(params)}}});" if params else f"  const {o.name}();")
    L.append("")
    for f in o.fields:
        L += dart_doc(f.doc, "  ")
        L.append(f"  final {dart_type(f.type, model)}{'' if f.required else '?'} {dart_ident(f.name)};")
    L.append("")
    L.append(f"  factory {o.name}.fromJson(Map<String, dynamic> json) => {o.name}(")
    for f in o.fields:
        src = f"json['{f.name}']"
        conv = dart_from(f.type, model, src)
        if not f.required:
            conv = f"{src} == null ? null : {conv}"
        L.append(f"        {dart_ident(f.name)}: {conv},")
    L.append("      );")
    L.append("")
    L.append(("  @override\n" if o.is_payload else "") + "  Map<String, dynamic> toJson() => {")
    for f in o.fields:
        ident = dart_ident(f.name)
        if f.required:
            L.append(f"        '{f.name}': {dart_to(f.type, model, ident)},")
        else:
            L.append(f"        if ({ident} != null) '{f.name}': {dart_to(f.type, model, ident + '!')},")
    L += ["      };", "}", ""]
    return L
