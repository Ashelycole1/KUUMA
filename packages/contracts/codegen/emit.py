def py_field(n: str) -> str:
    s = camel_to_snake(n)
    return s + "_" if s in PY_RESERVED else s


def py_type(t, model: Model) -> str:
    if isinstance(t, TRef):
        return t.name
    if isinstance(t, TList):
        return f"list[{py_type(t.item, model)}]"
    return {"string": "str", "integer": "int", "number": "float", "boolean": "bool"}[t.kind]


def emit_python(model: Model) -> dict[str, str]:
    L = [
        f"# {HEADER}",
        '"""Kuuma contract types (pydantic v2)."""',
        "",
        "from __future__ import annotations",
        "",
        "from dataclasses import dataclass",
        "from enum import StrEnum",
        "from typing import Annotated, Any, Generic, Literal, TypeVar",
        "",
        "from pydantic import BaseModel, ConfigDict, Field, StringConstraints",
        "",
        "",
        "class ContractModel(BaseModel):",
        '    """Base for every contract object: camelCase on the wire, unknown fields refused."""',
        "",
        '    model_config = ConfigDict(populate_by_name=True, extra="forbid", frozen=True)',
        "",
        "    def to_wire(self) -> dict[str, Any]:",
        '        return self.model_dump(by_alias=True, exclude_none=True, mode="json")',
        "",
        "",
    ]
    for a in model.sorted_types("alias"):
        if a.pattern:
            L.append(f"{a.name} = Annotated[str, StringConstraints(pattern={a.pattern!r})]")
        else:
            L.append(f"{a.name} = str")
        for d in doc_lines(a.doc):
            L.append(f"# {d}")
        L.append("")
    L.append("")
    for e in model.sorted_types("enum"):
        L += [f"class {e.name}(StrEnum):"]
        if e.doc:
            L.append(f'    """{e.doc}"""')
            L.append("")
        for v in e.values:
            L.append(f"    {v.upper()} = {v!r}")
        L += ["", ""]
    objects = [o for o in model.sorted_types("object")]
    for o in objects:
        L += py_object(o, model)
    # Envelope + events
    L += [
        'P = TypeVar("P", bound=ContractModel)',
        "",
        "",
        "class Envelope(ContractModel, Generic[P]):",
        '    """Wraps every event. No field may hold a real name, phone number or message text."""',
        "",
        '    event_id: Uuid = Field(alias="eventId")',
        "    type: str",
        "    version: int",
        '    occurred_at: Timestamp = Field(alias="occurredAt")',
        '    device_id: Uuid = Field(alias="deviceId")',
        '    case_id: Uuid | None = Field(default=None, alias="caseId")',
        "    payload: P",
        "",
        "",
    ]
    for e in model.events:
        L += [f"class {e.title}(Envelope[{e.payload}]):"]
        if e.doc:
            L += [f'    """{e.doc}"""', ""]
        L += [
            f'    type: Literal["{e.type}"] = "{e.type}"',
            f"    version: Literal[{e.version}] = {e.version}",
            "",
            "",
        ]
    L += [
        "@dataclass(frozen=True)",
        "class EventSpec:",
        "    type: str",
        "    version: int",
        "    publisher: str",
        "    where: str",
        "    phone_only: bool",
        "    model: type[Envelope[Any]]",
        "    payload: type[ContractModel]",
        "",
        "",
        "EVENTS: dict[tuple[str, int], EventSpec] = {",
    ]
    for e in model.events:
        L.append(
            f'    ("{e.type}", {e.version}): EventSpec("{e.type}", {e.version}, "{e.publisher}", "{e.where}", '
            f"{e.phone_only}, {e.title}, {e.payload}),"
        )
    L += [
        "}",
        "",
        f"NAMESPACES: tuple[str, ...] = {tuple(model.namespaces)!r}",
        "",
        "",
        "def event_spec(type_: str, version: int = 1) -> EventSpec:",
        "    try:",
        "        return EVENTS[(type_, version)]",
        "    except KeyError:",
        '        raise KeyError(f"unknown event {type_}.v{version}") from None',
        "",
    ]
    return {
        "kuuma_contracts/models.py": "\n".join(L),
        "kuuma_contracts/schema_bundle.json": schema_bundle_json(model),
    }


def py_object(o: ObjectDef, model: Model) -> list[str]:
    L = [f"class {o.name}(ContractModel):"]
    if o.doc:
        L += [f'    """{o.doc}"""', ""]
    for f in o.fields:
        name = py_field(f.name)
        t = py_type(f.type, model)
        alias = f', alias="{f.name}"' if name != f.name else ""
        if f.required:
            L.append(f"    {name}: {t}" + (f" = Field({alias[2:]})" if alias else ""))
        else:
            L.append(f"    {name}: {t} | None = Field(default=None{alias})")
    if not o.fields:
        L.append("    pass")
    L += ["", ""]
    return L


# ============================================================================ TypeScript


def ts_type(t, model: Model) -> str:
    if isinstance(t, TRef):
        return t.name
    if isinstance(t, TList):
        return f"{ts_type(t.item, model)}[]"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean"}[t.kind]


def ts_doc(text: str, indent: str = "") -> list[str]:
    lines = doc_lines(text)
    if not lines:
        return []
    return [f"{indent}/**", *[f"{indent} * {line}".rstrip() for line in lines], f"{indent} */"]


def emit_ts(model: Model) -> dict[str, str]:
    L = [f"// {HEADER}", ""]
    for a in model.sorted_types("alias"):
        L += ts_doc(a.doc)
        L += [f"export type {a.name} = string;", ""]
    L.append("export const PATTERNS = {")
    for a in model.sorted_types("alias"):
        if a.pattern:
            L.append(f"  {a.name}: {json.dumps(a.pattern)},")
    L += ["} as const;", ""]
    for e in model.sorted_types("enum"):
        const = e.name[0].lower() + e.name[1:] + "Values"
        L += ts_doc(e.doc)
        L += [
            f"export const {const} = [{', '.join(json.dumps(v) for v in e.values)}] as const;",
            f"export type {e.name} = (typeof {const})[number];",
            "",
        ]
    for o in model.sorted_types("object"):
        L += ts_doc(o.doc)
        L.append(f"export interface {o.name} {{")
        for f in o.fields:
            L += ts_doc(f.doc, "  ")
            L.append(f"  {f.name}{'' if f.required else '?'}: {ts_type(f.type, model)};")
        L += ["}", ""]
    L += [
        "export interface Envelope<T extends string, V extends number, P> {",
        "  eventId: Uuid;",
        "  type: T;",
        "  version: V;",
        "  occurredAt: Timestamp;",
        "  deviceId: Uuid;",
        "  caseId?: Uuid;",
        "  payload: P;",
        "}",
        "",
    ]
    for e in model.events:
        L += ts_doc(e.doc)
        L += [f'export type {e.title} = Envelope<"{e.type}", {e.version}, {e.payload}>;', ""]
    L += ["export type KuumaEvent ="]
    L += [f"  | {e.title}" for e in model.events]
    L[-1] += ";"
    L += ["", "export type PhoneOnlyEvent ="]
    po = [e for e in model.events if e.phone_only]
    L += [f"  | {e.title}" for e in po]
    L[-1] += ";"
    L += [
        "",
        "/** Events that may leave the phone. */",
        "export type CloudSendableEvent = Exclude<KuumaEvent, PhoneOnlyEvent>;",
        "",
        f"export const namespaceValues = [{', '.join(json.dumps(n) for n in model.namespaces)}] as const;",
        "export type Namespace = (typeof namespaceValues)[number];",
        "",
        "export interface EventSpec {",
        "  type: string;",
        "  version: number;",
        "  publisher: Namespace;",
        "  where: string;",
        "  phoneOnly: boolean;",
        "  title: string;",
        "  payload: string;",
        "}",
        "",
        "export const EVENTS: readonly EventSpec[] = " + json.dumps(event_meta(model), indent=2) + ";",
        "",
    ]
    return {"src/models.ts": "\n".join(L), "src/schema-bundle.json": schema_bundle_json(model)}


