def dart_ident(n: str) -> str:
    c = snake_to_camel(n)
    return c + "_" if c in DART_RESERVED else c


def dart_type(t, model: Model) -> str:
    if isinstance(t, TRef):
        tt = model.types[t.name]
        return "String" if isinstance(tt, AliasDef) else t.name
    if isinstance(t, TList):
        return f"List<{dart_type(t.item, model)}>"
    return {"string": "String", "integer": "int", "number": "double", "boolean": "bool"}[t.kind]


def dart_from(t, model: Model, expr: str) -> str:
    if isinstance(t, TList):
        inner = dart_from(t.item, model, "e")
        return f"({expr} as List<dynamic>).map((e) => {inner}).toList()"
    if isinstance(t, TRef):
        tt = model.types[t.name]
        if isinstance(tt, AliasDef):
            return f"{expr} as String"
        if isinstance(tt, EnumDef):
            return f"{t.name}.fromWire({expr} as String)"
        return f"{t.name}.fromJson({expr} as Map<String, dynamic>)"
    if t.kind == "number":
        return f"({expr} as num).toDouble()"
    return f"{expr} as {dart_type(t, model)}"


def dart_to(t, model: Model, expr: str) -> str:
    if isinstance(t, TList):
        inner = dart_to(t.item, model, "e")
        return expr if inner == "e" else f"{expr}.map((e) => {inner}).toList()"
    if isinstance(t, TRef):
        tt = model.types[t.name]
        if isinstance(tt, AliasDef):
            return expr
        if isinstance(tt, EnumDef):
            return f"{expr}.wire"
        return f"{expr}.toJson()"
    return expr


def dart_doc(text: str, indent: str = "") -> list[str]:
    return [f"{indent}/// {line}".rstrip() for line in doc_lines(text)]


def emit_dart(model: Model) -> dict[str, str]:
    L = [
        f"// {HEADER}",
        "// ignore_for_file: constant_identifier_names, lines_longer_than_80_chars",
        "",
        "part of '../kuuma_contracts.dart';",
        "",
    ]
    L += [
        "/// Patterns for string aliases (Uuid, OpaqueRef, ...), which Dart models as String.",
        "abstract final class ContractPatterns {",
    ]
    for a in model.sorted_types("alias"):
        if a.pattern:
            assert "'" not in a.pattern, f"{a.name}: pattern may not contain a single quote"
            L.append(f"  static final RegExp {a.name[0].lower() + a.name[1:]} = RegExp(r'{a.pattern}');")
    L += ["}", ""]
    for e in model.sorted_types("enum"):
        L += dart_doc(e.doc)
        L.append(f"enum {e.name} {{")
        L += [f"  {dart_ident(v)}('{v}')," for v in e.values]
        L[-1] = L[-1][:-1] + ";"
        L += [
            "",
            f"  const {e.name}(this.wire);",
            "",
            "  final String wire;",
            "",
            f"  static {e.name} fromWire(String wire) =>",
            "      values.firstWhere((v) => v.wire == wire,",
            f"          orElse: () => throw ArgumentError('Unknown {e.name}: $wire'));",
            "}",
            "",
        ]
    for o in model.sorted_types("object"):
        L += dart_object(o, model)
    L += [
        "/// Base of every event payload.",
        "sealed class EventPayload {",
        "  const EventPayload();",
        "  Map<String, dynamic> toJson();",
        "}",
        "",
        "/// May leave the phone.",
        "abstract class CloudSendablePayload extends EventPayload {",
        "  const CloudSendablePayload();",
        "}",
        "",
        "/// Must never leave the phone.",
        "abstract class PhoneOnlyPayload extends EventPayload {",
        "  const PhoneOnlyPayload();",
        "}",
        "",
        "/// Static description of one event type.",
        "class EventSpec<P extends EventPayload> {",
        "  const EventSpec(this.type, this.version, this.publisher, this.where, this.phoneOnly, this.fromJson);",
        "  final String type;",
        "  final int version;",
        "  final String publisher;",
        "  final String where;",
        "  final bool phoneOnly;",
        "  final P Function(Map<String, dynamic>) fromJson;",
        "}",
        "",
        "/// Wraps every event.",
        "class Envelope<P extends EventPayload> {",
        "  const Envelope({required this.eventId, required this.type, required this.version, required this.occurredAt,",
        "      required this.deviceId, this.caseId, required this.payload});",
        "  final String eventId;",
        "  final String type;",
        "  final int version;",
        "  final String occurredAt;",
        "  final String deviceId;",
        "  final String? caseId;",
        "  final P payload;",
        "",
        "  Map<String, dynamic> toJson() => {",
        "        'eventId': eventId, 'type': type, 'version': version, 'occurredAt': occurredAt,",
        "        'deviceId': deviceId, if (caseId != null) 'caseId': caseId, 'payload': payload.toJson(),",
        "      };",
        "",
        "  static Envelope<EventPayload> fromJson(Map<String, dynamic> json) {",
        "    final spec = Events.byType(json['type'] as String, json['version'] as int);",
        "    if (spec == null) throw ArgumentError('Unknown event ${json['type']}.v${json['version']}');",
        "    return Envelope<EventPayload>(",
        "      eventId: json['eventId'] as String,",
        "      type: json['type'] as String,",
        "      version: json['version'] as int,",
        "      occurredAt: json['occurredAt'] as String,",
        "      deviceId: json['deviceId'] as String,",
        "      caseId: json['caseId'] as String?,",
        "      payload: spec.fromJson(json['payload'] as Map<String, dynamic>),",
        "    );",
        "  }",
        "}",
        "",
        "abstract final class Events {",
    ]
    for e in model.events:
        name = snake_to_camel(e.type.replace(".", "_"))
        L.append(
            f"  static const EventSpec<{e.payload}> {name} = EventSpec('{e.type}', {e.version}, "
            f"'{e.publisher}', '{e.where}', {str(e.phone_only).lower()}, {e.payload}.fromJson);"
        )
    L += ["", "  static const List<EventSpec<EventPayload>> all = ["]
