"""Emitters: turn the contract Model into Kotlin, Dart, Python and TypeScript sources.

Output is deterministic (sorted, no timestamps) so the CI drift check can diff it.
"""

from __future__ import annotations

import json
import re

from model import AliasDef, EnumDef, Model, ObjectDef, TList, TRef

HEADER = "GENERATED by packages/contracts/codegen — DO NOT EDIT. Change the schemas and run `make gen`."


def camel_to_snake(s: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", s).lower()


def snake_to_camel(s: str) -> str:
    parts = s.split("_")
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def doc_lines(text: str) -> list[str]:
    return [line.strip() for line in text.strip().splitlines()] if text.strip() else []


def schema_bundle_json(model: Model) -> str:
    return json.dumps(dict(sorted(model.bundle.items())), indent=1, sort_keys=True, ensure_ascii=False) + "\n"


def event_meta(model: Model) -> list[dict]:
    return [
        {
            "type": e.type,
            "version": e.version,
            "publisher": e.publisher,
            "where": e.where,
            "phoneOnly": e.phone_only,
            "title": e.title,
            "payload": e.payload,
        }
        for e in model.events
    ]


