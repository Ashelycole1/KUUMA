"""Bundle packages/lang/data/*.yaml into one JSON document for the Kotlin, Dart and Python loaders.

    python packages/lang/tools/build.py          # write the bundles (part of `make gen`)
    python packages/lang/tools/build.py --check  # fail if bundles are stale (CI drift check)

Also fails if a YAML file disagrees with its contract enum.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import yaml

LANG = Path(__file__).resolve().parent.parent
REPO = LANG.parent.parent
DATA = LANG / "data"
TYPES = REPO / "packages" / "contracts" / "schemas" / "types"
HEADER = "GENERATED by packages/lang/tools/build.py — DO NOT EDIT. Edit packages/lang/data/*.yaml and run `make gen`."

OUTPUTS = {
    "kotlin": LANG / "kotlin/src/main/resources/kuuma/lang.json",
    "python": LANG / "python/kuuma_lang/lang.json",
    "dart": LANG / "dart/lib/src/lang_data.g.dart",
}


def contract_schema(title: str) -> dict:
    for p in TYPES.glob("*.json"):
        doc = json.loads(p.read_text(encoding="utf-8"))
        if doc["title"] == title:
            return doc
    raise SystemExit(f"no contract type titled {title}")


def load_data() -> dict:
    out = {}
    for p in sorted(DATA.glob("*.yaml")):
        doc = yaml.safe_load(p.read_text(encoding="utf-8"))
        ids = [v["id"] for v in doc["values"]]
        if len(ids) != len(set(ids)):
            raise SystemExit(f"{p.name}: duplicate ids")
        schema = contract_schema(doc["contract"])
        if "enum" in schema:
            if ids != schema["enum"]:
                raise SystemExit(
                    f"{p.name}: values {ids} differ from contract {doc['contract']} {schema['enum']}"
                )
        elif "pattern" in schema:
            bad = [i for i in ids if not re.match(schema["pattern"], i)]
            if bad:
                raise SystemExit(f"{p.name}: ids {bad} do not match the {doc['contract']} pattern")
        out[p.stem] = doc
    return out


def render() -> dict[Path, str]:
    data = load_data()
    js = json.dumps(data, indent=1, sort_keys=True, ensure_ascii=False) + "\n"
    dart = f"// {HEADER}\n\npart of '../kuuma_lang.dart';\n\nconst String _kuumaLangJson = r'''\n{js}''';\n"
    return {OUTPUTS["kotlin"]: js, OUTPUTS["python"]: js, OUTPUTS["dart"]: dart}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    files = render()
    stale = []
    for path, text in files.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            if args.check:
                stale.append(path.relative_to(REPO).as_posix())
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8", newline="\n")
    if stale:
        print("kuuma-lang bundles are stale — run `make gen`:", *stale, sep="\n  ", file=sys.stderr)
        return 1
    print("lang: bundles " + ("up to date" if args.check else "written"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
